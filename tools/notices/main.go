// Command notices writes THIRD_PARTY_NOTICES.md: every Go module that is linked
// into the release binaries, with its license (detected from its LICENSE file)
// and the full license text. The font bundled in web/fonts is listed as well.
//
//	go run ./tools/notices            # rewrites THIRD_PARTY_NOTICES.md
//	go run ./tools/notices -check     # fails when the file is out of date
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct {
	Path, Version, Dir, License, Text string
}

func main() {
	check := flag.Bool("check", false, "fail when THIRD_PARTY_NOTICES.md is out of date")
	flag.Parse()

	mods, err := linkedModules()
	if err != nil {
		fail(err)
	}
	out := render(mods)
	if *check {
		have, _ := os.ReadFile("THIRD_PARTY_NOTICES.md")
		if !bytes.Equal(bytes.ReplaceAll(have, []byte("\r\n"), []byte("\n")), []byte(out)) {
			fail(fmt.Errorf("THIRD_PARTY_NOTICES.md is out of date; run: go run ./tools/notices"))
		}
		return
	}
	if err := os.WriteFile("THIRD_PARTY_NOTICES.md", []byte(out), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote THIRD_PARTY_NOTICES.md (%d modules)\n", len(mods))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "notices:", err)
	os.Exit(1)
}

// linkedModules lists the modules of the packages the Windows release binaries are built from.
func linkedModules() ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}", "./cmd/datacodex-notify", "./cmd/datacodex-notify-cli")
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS=windows", "GOARCH=amd64")
	data, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list failed: %w", err)
	}
	seen := map[string]bool{}
	var mods []module
	for _, line := range strings.Split(string(data), "\n") {
		parts := strings.Split(strings.TrimSpace(line), "|")
		if len(parts) != 3 || seen[parts[0]] {
			continue
		}
		seen[parts[0]] = true
		m := module{Path: parts[0], Version: parts[1], Dir: parts[2]}
		m.License, m.Text = readLicense(m.Dir)
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return mods, nil
}

func readLicense(dir string) (name, text string) {
	for _, file := range []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING", "license"} {
		data, err := os.ReadFile(filepath.Join(dir, file))
		if err == nil {
			t := strings.TrimSpace(strings.ReplaceAll(string(data), "\r\n", "\n"))
			return detect(t), t
		}
	}
	return "UNKNOWN (no license file found)", ""
}

func detect(text string) string {
	lower := strings.ToLower(text)
	switch {
	case strings.Contains(lower, "mozilla public license") && strings.Contains(lower, "2.0"):
		return "MPL-2.0"
	case strings.Contains(lower, "apache license") && strings.Contains(lower, "version 2.0"):
		return "Apache-2.0"
	case strings.Contains(lower, "permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(lower, "redistribution and use in source and binary forms") && strings.Contains(lower, "neither the name"):
		return "BSD-3-Clause"
	case strings.Contains(lower, "redistribution and use in source and binary forms"):
		return "BSD-2-Clause"
	case strings.Contains(lower, "gnu general public license") && strings.Contains(lower, "version 3"):
		return "GPL-3.0"
	case strings.Contains(lower, "permission to use, copy, modify, and/or distribute"),
		strings.Contains(lower, "permission to use, copy, modify, and distribute this software for any"):
		return "ISC"
	case strings.Contains(lower, "unlicense"):
		return "Unlicense"
	}
	return "see license text"
}

func render(mods []module) string {
	var b strings.Builder
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("DataCodex Notify is free software released under the GNU General Public License, version 3 only (GPL-3.0-only); see `LICENSE`. The release binaries are distributed under those terms, and the corresponding source code is the repository at <https://github.com/datacodexlab/datacodex-notify>. They include the following third-party software.\n")
	b.WriteString("This file is generated by `go run ./tools/notices` from the modules linked into the Windows release binaries.\n\n")
	b.WriteString("## Summary\n\n| Module | Version | License |\n|---|---|---|\n")
	for _, m := range mods {
		fmt.Fprintf(&b, "| [%s](https://pkg.go.dev/%s) | %s | %s |\n", m.Path, m.Path, m.Version, m.License)
	}
	b.WriteString("| IBM Plex Sans Arabic (font, `web/fonts`) | - | SIL OFL 1.1 |\n")
	b.WriteString("\n## whatsmeow (MPL-2.0)\n\n")
	b.WriteString("WhatsApp connectivity uses [whatsmeow](https://github.com/tulir/whatsmeow), licensed under the Mozilla Public License 2.0. ")
	b.WriteString("DataCodex Notify uses it unmodified, as a Go module dependency. Its source code is available at <https://github.com/tulir/whatsmeow>; ")
	b.WriteString("the exact version used is pinned in `go.mod`. The MPL applies to whatsmeow's own files; MPL-2.0 allows the combined program to be distributed under the GPL.\n")
	for _, m := range mods {
		if m.License == "GPL-3.0" {
			fmt.Fprintf(&b, "\n## %s (GPL-3.0)\n\n", m.Path)
			b.WriteString("whatsmeow depends on this module (version 3 of the license, with no \"or later\" option), so it is linked into the release binaries. This is why DataCodex Notify itself is licensed GPL-3.0-only: the binaries are distributed under the GPL-3.0 and the corresponding source code is available in the repository.\n")
		}
	}
	b.WriteString("\n## IBM Plex Sans Arabic (SIL OFL 1.1)\n\n")
	b.WriteString("The admin window bundles the IBM Plex Sans Arabic font. Its license is in `web/fonts/LICENSE-OFL.txt`.\n")
	b.WriteString("\n## License texts\n")
	for _, m := range mods {
		fmt.Fprintf(&b, "\n### %s %s\n\nLicense: %s\n\n", m.Path, m.Version, m.License)
		if m.Text == "" {
			b.WriteString("No license file was found in the module; see its repository.\n")
			continue
		}
		b.WriteString("```text\n" + m.Text + "\n```\n")
	}
	return b.String()
}
